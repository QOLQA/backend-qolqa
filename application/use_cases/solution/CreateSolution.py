from application.dtos.solution.commands import CreateSolutionCommand
from domain.entities.SolutionEntity import SolutionEntity
from domain.repositories.solution.repo import ISolutionRepository


async def create_solution(
    repository: ISolutionRepository,
    command: CreateSolutionCommand,
) -> SolutionEntity:
    """Create a new solution."""
    entity = SolutionEntity.create(
        id="",  # Will be generated by MongoDB
        name=command.name,
        user_id=command.user_id,
        last_version_saved=command.last_version_saved,
        src_img=command.src_img,
    )

    return await repository.save(entity)

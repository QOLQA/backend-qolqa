from application.dtos.auth.commands import RegisterCommand
from domain.entities.auth.UserEntity import UserEntity
from domain.repositories.user.repo import IUserRepository


async def register_user(
    repository: IUserRepository,
    command: RegisterCommand,
) -> UserEntity:
    """
    Register a new local (email/password) user.

    Domain validation happens in the entity factory (empty username/email
    rejected, fields normalized); the repository handles duplicate checks and
    password hashing before persistence.

    Args:
        repository: IUserRepository — handles duplicate checks and password hashing
        command: RegisterCommand with validated user data

    Returns:
        UserEntity representing the newly created user
    """
    # Domain-level validation and normalization (lowercase, strip).
    # The entity itself is not persisted from here — the repository builds the
    # document and hashes the password, keeping the plain password out of the
    # domain layer and out of the entity.
    UserEntity.create_local(
        id='',  # Will be generated by MongoDB
        username=command.username,
        email=command.email,
        full_name=command.full_name,
    )

    return await repository.add_local_user(
        username=command.username,
        email=command.email,
        full_name=command.full_name,
        password=command.password,
    )

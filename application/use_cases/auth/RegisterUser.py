from application.dtos.auth.commands import CreateUserCommand
from domain.entities.auth.UserEntity import UserEntity
from domain.repositories.user.repo import IUserRepository


async def register_user(
    repository: IUserRepository,
    command: CreateUserCommand,
) -> UserEntity:
    """
    Register a new user.

    Args:
        repository: IUserRepository — handles duplicate checks and password hashing
        command: CreateUserCommand with validated user data

    Returns:
        UserEntity representing the newly created user
    """
    entity = UserEntity.create_local(
        id="",  # Will be generated by MongoDB
        username=command.username,
        email=command.email,
        full_name=command.full_name,
    )
    return await repository.save(entity)

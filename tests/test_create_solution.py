"""Tests pinning the POST /solutions 500 ("Solution ID is required").

CreateSolution passed id="" ("Will be generated by MongoDB") but the domain
factory requires a non-empty id, and SolutionRepoImpl.save() re-fetches by
entity.id — both break on an empty id. The fix mirrors CreateVersion and
CreateQuery: the use case generates the id (str(ObjectId())).
"""

from datetime import UTC, datetime
from unittest.mock import AsyncMock

import pytest
from bson import ObjectId

from application.dtos.solution.commands import CreateSolutionCommand
from application.use_cases.solution.CreateSolution import create_solution


def _command() -> CreateSolutionCommand:
    return CreateSolutionCommand(
        name="Mi Solución",
        user_id="6b09c552ff7a9c76e52aa22a",
        last_version_saved="v1",
        src_img="http://example.com/img.png",
    )


class TestCreateSolutionUseCase:
    """create_solution must produce a persistable entity with a real id."""

    @pytest.mark.asyncio
    async def test_create_solution_generates_valid_objectid(self):
        mock_repo = AsyncMock()
        mock_repo.save = AsyncMock(side_effect=lambda entity: entity)

        entity = await create_solution(mock_repo, _command())

        # The id must be a valid, non-empty ObjectId string (factory + repo
        # re-fetch both require it)
        assert entity.id
        assert ObjectId.is_valid(entity.id)
        assert entity.name == "Mi Solución"
        mock_repo.save.assert_awaited_once()

    @pytest.mark.asyncio
    async def test_create_solution_returns_persisted_entity(self):
        marker_created_at = datetime.now(UTC)

        class _Persisted:
            id = str(ObjectId())
            name = "Mi Solución"
            user_id = "6b09c552ff7a9c76e52aa22a"
            last_version_saved = "v1"
            src_img = "http://example.com/img.png"
            last_updated_at = marker_created_at
            versions: list = []

        persisted = _Persisted()
        mock_repo = AsyncMock()
        mock_repo.save = AsyncMock(return_value=persisted)

        entity = await create_solution(mock_repo, _command())

        assert entity is persisted

    @pytest.mark.asyncio
    async def test_create_solution_still_rejects_empty_name(self):
        mock_repo = AsyncMock()
        command = CreateSolutionCommand(
            name="  ",
            user_id="6b09c552ff7a9c76e52aa22a",
            last_version_saved="v1",
            src_img="http://example.com/img.png",
        )
        with pytest.raises(ValueError):
            await create_solution(mock_repo, command)
        mock_repo.save.assert_not_awaited()
